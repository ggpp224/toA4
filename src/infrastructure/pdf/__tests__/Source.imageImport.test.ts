describe("source kind detection", () => {
  it("recognizes pdf, png, and jpeg magic bytes", () => {
    expect(detectSourceKind(new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2d]))).toBe("pdf");
    expect(detectSourceKind(PNG_1x1)).toBe("png");
    expect(detectSourceKind(JPEG_1x1)).toBe("jpeg");
    expect(detectSourceKind(new Uint8Array([0x00, 0x01]), { name: "x.gif" })).toBeNull();
  });

  it("falls back to extension when bytes are ambiguous", () => {
    expect(detectSourceKind(new Uint8Array([0x00]), { name: "scan.PNG", type: "" })).toBe("png");
    expect(detectSourceKind(new Uint8Array([0x00]), { name: "a.jpeg" })).toBe("jpeg");
  });
});

describe("image import", () => {
  it("wraps a png as a one-page pdf with matching point size", async () => {
    const pdfBytes = await imageToPdf(PNG_1x1, "png");
    const doc = await PDFDocument.load(pdfBytes);
    expect(doc.getPageCount()).toBe(1);
    const page = doc.getPage(0);
    expect(page.getWidth()).toBe(1);
    expect(page.getHeight()).toBe(1);
  });

  it("wraps a jpeg as a one-page pdf", async () => {
    const pdfBytes = await imageToPdf(JPEG_1x1, "jpeg");
    const doc = await PDFDocument.load(pdfBytes);
    expect(doc.getPageCount()).toBe(1);
  });
});
